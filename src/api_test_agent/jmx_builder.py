"""Generate JMeter .jmx test plans from a TestPlan."""

from __future__ import annotations

import json
import xml.etree.ElementTree as ET
from pathlib import Path
from typing import Any

from api_test_agent.models import TestCase, TestPlan

JMETER_TEST_PLAN = "org.apache.jmeter.testelement.TestPlan"
THREAD_GROUP = "org.apache.jmeter.threads.ThreadGroup"
LOOP_CONTROLLER = "org.apache.jmeter.control.LoopController"
HTTP_SAMPLER = "org.apache.jmeter.protocol.http.sampler.HTTPSamplerProxy"
HEADER_MANAGER = "org.apache.jmeter.protocol.http.control.HeaderManager"
JSON_ASSERTION = "org.apache.jmeter.assertions.JSONPathAssertion"
RESPONSE_ASSERTION = "org.apache.jmeter.assertions.ResponseAssertion"
HASH_TREE = "org.apache.jmeter.testelement.hash_tree.HashTree"


def _prop(name: str, value: str | int | bool, element_type: str = "string") -> ET.Element:
    el = ET.Element("stringProp", name=name)
    if element_type == "bool":
        el = ET.Element("boolProp", name=name)
        el.text = "true" if value else "false"
    elif element_type == "int":
        el = ET.Element("intProp", name=name)
        el.text = str(value)
    else:
        el.text = str(value)
    return el


def _elem(testclass: str, testname: str, **props: Any) -> ET.Element:
    e = ET.Element("elementProp", name=props.pop("name", ""), elementType=testclass)
    e.set("name", props.pop("ep_name", testname))
    e.set("elementType", testclass)
    gc = ET.SubElement(e, "stringProp", name="TestPlan.comments")
    gc.text = ""
    for k, v in props.items():
        if k.endswith("_bool"):
            e.append(_prop(k[:-5], v, "bool"))
        elif k.endswith("_int"):
            e.append(_prop(k[:-4], v, "int"))
        else:
            e.append(_prop(k, v))
    return e


def jmeter_load_properties(profile: str, threads: int = 1, ramp_seconds: int = 1, loops: int = 1) -> dict[str, int]:
    """Build -J properties for yaymeter parametric JMX."""
    if profile == "functional":
        return {
            "yaymeter.threads": 1,
            "yaymeter.ramp_seconds": 1,
            "yaymeter.loops": 1,
        }
    return {
        "yaymeter.threads": threads,
        "yaymeter.ramp_seconds": ramp_seconds,
        "yaymeter.loops": loops,
    }


def build_jmx(
    plan: TestPlan,
    profile: str = "functional",
    auth_header_env: str = "API_TEST_AUTH_TOKEN",
    parametric: bool = True,
) -> str:
    """Return JMX XML string."""
    root = ET.Element(
        "jmeterTestPlan",
        version="1.2",
        properties="5.0",
        jmeter="5.6.3",
    )
    hash_tree = ET.SubElement(root, "hashTree")

    test_plan = ET.SubElement(hash_tree, "TestPlan", guiclass="TestPlanGui", testclass=JMETER_TEST_PLAN, testname="Yaymeter Plan", enabled="true")
    ET.SubElement(test_plan, "boolProp", name="TestPlan.functional_mode").text = "false"
    ET.SubElement(test_plan, "boolProp", name="TestPlan.serialize_threadgroups").text = "false"
    ET.SubElement(test_plan, "stringProp", name="TestPlan.comments").text = "Generated by yaymeter"
    ET.SubElement(test_plan, "stringProp", name="TestPlan.user_define_classpath").text = ""

    tp_ht = ET.SubElement(hash_tree, "hashTree")

    if parametric:
        threads = "${__P(yaymeter.threads,1)}"
        ramp = "${__P(yaymeter.ramp_seconds,1)}"
        loops = "${__P(yaymeter.loops,1)}"
        use_scheduler = False
        duration = ""
    else:
        threads = 1
        ramp = 1
        loops = 1
        duration = ""
        use_scheduler = False
        if profile == "performance":
            threads = 10
            ramp = 30
            loops = 20

    tg = ET.SubElement(
        tp_ht,
        "ThreadGroup",
        guiclass="ThreadGroupGui",
        testclass=THREAD_GROUP,
        testname="Thread Group",
        enabled="true",
    )
    ET.SubElement(tg, "stringProp", name="ThreadGroup.on_sample_error").text = "continue"
    ET.SubElement(tg, "elementProp", name="ThreadGroup.main_controller", elementType=LOOP_CONTROLLER)
    lc = tg.find("elementProp[@name='ThreadGroup.main_controller']")
    ET.SubElement(lc, "boolProp", name="LoopController.continue_forever").text = "false"
    ET.SubElement(lc, "stringProp", name="LoopController.loops").text = str(loops)
    ET.SubElement(tg, "stringProp", name="ThreadGroup.num_threads").text = str(threads)
    ET.SubElement(tg, "stringProp", name="ThreadGroup.ramp_time").text = str(ramp)
    ET.SubElement(tg, "boolProp", name="ThreadGroup.scheduler").text = "true" if use_scheduler else "false"
    if use_scheduler and duration:
        ET.SubElement(tg, "stringProp", name="ThreadGroup.duration").text = str(duration)
    ET.SubElement(tg, "boolProp", name="ThreadGroup.same_user_on_next_iteration").text = "true"

    tg_ht = ET.SubElement(tp_ht, "hashTree")

    # Default JSON content-type header manager
    hm = ET.SubElement(
        tg_ht,
        "HeaderManager",
        guiclass="HeaderPanel",
        testclass=HEADER_MANAGER,
        testname="HTTP Header Manager",
        enabled="true",
    )
    coll = ET.SubElement(hm, "collectionProp", name="HeaderManager.headers")
    for hname, hval in [("Content-Type", "application/json"), ("Authorization", f"${{{auth_header_env}}}")]:
        he = ET.SubElement(coll, "elementProp", name="", elementType="Header")
        ET.SubElement(he, "stringProp", name="Header.name").text = hname
        ET.SubElement(he, "stringProp", name="Header.value").text = hval
    ET.SubElement(tg_ht, "hashTree")

    executable = [t for t in plan.test_cases if not t.blocked and t.category.value != "contract"]
    if profile == "functional":
        executable = [t for t in executable if t.category.value != "performance"]

    for test in executable:
        _add_http_sampler(tg_ht, plan.base_url, test)

    ET.indent(root, space="  ")
    return ET.tostring(root, encoding="unicode", xml_declaration=True)


def _add_http_sampler(parent_ht: ET.Element, base_url: str, test: TestCase) -> None:
    from urllib.parse import urlencode, urlparse

    parsed = urlparse(base_url)
    domain = parsed.hostname or "localhost"
    port = str(parsed.port or (443 if parsed.scheme == "https" else 80))
    protocol = parsed.scheme or "http"
    path = (parsed.path or "").rstrip("/") + test.request.path
    if test.request.query:
        path += "?" + urlencode(test.request.query)

    sampler = ET.SubElement(
        parent_ht,
        "HTTPSamplerProxy",
        guiclass="HttpTestSampleGui",
        testclass=HTTP_SAMPLER,
        testname=test.test_id,
        enabled="true",
    )
    ET.SubElement(sampler, "stringProp", name="HTTPSampler.domain").text = domain
    ET.SubElement(sampler, "stringProp", name="HTTPSampler.port").text = port
    ET.SubElement(sampler, "stringProp", name="HTTPSampler.protocol").text = protocol
    ET.SubElement(sampler, "stringProp", name="HTTPSampler.path").text = path
    ET.SubElement(sampler, "stringProp", name="HTTPSampler.method").text = test.request.method.upper()
    ET.SubElement(sampler, "boolProp", name="HTTPSampler.follow_redirects").text = "true"
    ET.SubElement(sampler, "boolProp", name="HTTPSampler.use_keepalive").text = "true"
    if test.request.body is not None:
        body_str = json.dumps(test.request.body) if not isinstance(test.request.body, str) else test.request.body
        ET.SubElement(sampler, "boolProp", name="HTTPSampler.postBodyRaw").text = "true"
        args = ET.SubElement(sampler, "elementProp", name="HTTPsampler.Arguments", elementType="Arguments")
        coll = ET.SubElement(args, "collectionProp", name="Arguments.arguments")
        arg = ET.SubElement(coll, "elementProp", name="", elementType="HTTPArgument")
        ET.SubElement(arg, "boolProp", name="HTTPArgument.always_encode").text = "false"
        ET.SubElement(arg, "stringProp", name="Argument.value").text = body_str
        ET.SubElement(arg, "stringProp", name="Argument.metadata").text = "="

    s_ht = ET.SubElement(parent_ht, "hashTree")

    if test.expected.status_codes:
        ra = ET.SubElement(
            s_ht,
            "ResponseAssertion",
            guiclass="AssertionGui",
            testclass=RESPONSE_ASSERTION,
            testname="Response Status",
            enabled="true",
        )
        ET.SubElement(ra, "collectionProp", name="Assertion.test_strings")
        coll = ra.find("collectionProp[@name='Assertion.test_strings']")
        for code in test.expected.status_codes:
            el = ET.SubElement(coll, "stringProp", name=str(code))
            el.text = str(code)
        ET.SubElement(ra, "stringProp", name="Assertion.custom_message").text = ""
        ET.SubElement(ra, "stringProp", name="Assertion.test_field").text = "Assertion.response_code"
        ET.SubElement(ra, "boolProp", name="Assertion.assume_success").text = "false"
        ET.SubElement(ra, "intProp", name="Assertion.test_type").text = "8"  # contains / matches codes

    ET.SubElement(s_ht, "hashTree")


def write_jmx(
    plan: TestPlan,
    path: Path | str,
    profile: str = "functional",
    parametric: bool = True,
) -> Path:
    p = Path(path)
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(build_jmx(plan, profile, parametric=parametric), encoding="utf-8")
    return p
